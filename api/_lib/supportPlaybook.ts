export function buildSupportPlaybookPrompt(): string {
  return modules
    .map((module) => {
      const bullets = module.guidance.map((item) => `- ${item}`).join('\n');
      return `【${module.title}】\n${bullets}`;
    })
    .join('\n\n');
}
